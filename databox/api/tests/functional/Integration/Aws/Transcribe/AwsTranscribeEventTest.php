    public function testUnsignedOrForgedMessagesAreRejected(): void
    {
        self::enableFixtures();

        $queueName = 'p2';
        $inMemoryTransport = $this->interceptMessengerEvents($queueName);

        $apiClient = static::createClient();
        $apiClient->disableReboot();

        $wsIntegration = $this->createIntegration();
        $payload = json_encode([
            'Type' => 'SubscriptionConfirmation',
            'MessageId' => '425ad1a8-55ce-4186-b15c-01ef9e54301f',
            'Token' => 'token',
            'TopicArn' => 'arn:aws:sns:eu-west-3:122649456891:test',
            'Message' => 'You have chosen to subscribe to the topic.',
            'SubscribeURL' => 'https://sns.eu-west-3.amazonaws.com/?Action=ConfirmSubscription&Token=token',
            'Timestamp' => '2023-01-03T09:08:29.319Z',
            'SignatureVersion' => '1',
        ], JSON_THROW_ON_ERROR);
        $signed = json_decode(self::sign($payload), true, 512, JSON_THROW_ON_ERROR);

        $forgedKey = openssl_pkey_new(['private_key_bits' => 2048, 'private_key_type' => OPENSSL_KEYTYPE_RSA]);
        $rejected = [
            'not JSON' => 'not JSON',
            'not an SNS message' => '{"foo": "bar"}',
            'unsigned' => $payload,
            'signed by another key' => self::sign($payload, $forgedKey),
            'altered after signing' => json_encode([...$signed, 'SubscribeURL' => 'https://sns.eu-west-3.amazonaws.com/?Action=ConfirmSubscription&Token=other'], JSON_THROW_ON_ERROR),
            'certificate outside of AWS SNS' => json_encode([...$signed, 'SigningCertURL' => 'https://example.com/SimpleNotificationService-test.pem'], JSON_THROW_ON_ERROR),
            'unknown certificate' => json_encode([...$signed, 'SigningCertURL' => 'https://sns.eu-west-3.amazonaws.com/SimpleNotificationService-other.pem'], JSON_THROW_ON_ERROR),
        ];
        foreach ($rejected as $case => $body) {
            $this->triggerEvent($apiClient, $wsIntegration->getId(), $body);
            $this->assertResponseStatusCodeSame(403, $case);
        }

        $this->assertSame([], $inMemoryTransport->getSent());
        $this->assertHasData($wsIntegration->getId(), AwsTranscribeEventHandler::DATA_EVENT_MESSAGE, 0);
    }
