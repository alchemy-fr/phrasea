    /**
     * The payload with its "SigningCertURL" and "Signature" set as AWS SNS would.
     */
    private static function sign(string $payload, ?\OpenSSLAsymmetricKey $key = null): string
    {
        $data = json_decode($payload, true, 512, JSON_THROW_ON_ERROR);
        $data['SigningCertURL'] = self::CERT_URL;
        unset($data['Signature']);
        $stringToSign = new MessageValidator()->getStringToSign(new Message([...$data, 'Signature' => '']));
        openssl_sign($stringToSign, $signature, $key ?? self::$privateKey, OPENSSL_ALGO_SHA1);
        $data['Signature'] = base64_encode($signature);

        return json_encode($data, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }

