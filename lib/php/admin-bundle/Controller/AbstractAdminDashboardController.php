<?php

declare(strict_types=1);

namespace Alchemy\AdminBundle\Controller;

use Alchemy\AdminBundle\AdminConfigRegistry;
use Alchemy\AdminBundle\Home\HomeActivityBlock;
use Alchemy\AdminBundle\Home\HomeActivityItem;
use Alchemy\AdminBundle\Home\HomeStat;
use Alchemy\AdminBundle\Utils\UserDisplayNameResolver;
use Alchemy\AuthBundle\Security\JwtUser;
use Alchemy\ConfiguratorBundle\Controller\ConfiguratorEntryCrudController;
use Alchemy\MessengerBundle\Controller\MessengerMessageCrudController;
use Alchemy\MessengerBundle\Entity\MessengerMessage;
use Doctrine\ORM\EntityManagerInterface;
use EasyCorp\Bundle\EasyAdminBundle\Config\Action;
use EasyCorp\Bundle\EasyAdminBundle\Config\Crud;
use EasyCorp\Bundle\EasyAdminBundle\Config\Dashboard;
use EasyCorp\Bundle\EasyAdminBundle\Config\Menu\RouteMenuItem;
use EasyCorp\Bundle\EasyAdminBundle\Config\Menu\SubMenuItem;
use EasyCorp\Bundle\EasyAdminBundle\Config\MenuItem;
use EasyCorp\Bundle\EasyAdminBundle\Config\UserMenu;
use EasyCorp\Bundle\EasyAdminBundle\Contracts\Menu\MenuItemInterface;
use EasyCorp\Bundle\EasyAdminBundle\Controller\AbstractDashboardController;
use EasyCorp\Bundle\EasyAdminBundle\Router\AdminUrlGenerator;
use Psr\Log\LoggerInterface;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Security\Core\User\UserInterface;
use Symfony\Contracts\Service\Attribute\Required;

abstract class AbstractAdminDashboardController extends AbstractDashboardController
{
    private AdminConfigRegistry $adminConfigRegistry;
    private UserDisplayNameResolver $userDisplayNameResolver;
    private LoggerInterface $logger;

    /**
     * Routed by the #[AdminDashboard] attribute of the application dashboard: a #[Route] here
     * would replace the route generated by EasyAdmin, which creates the admin context.
     */
    public function index(): Response
    {
        $stats = [];
        foreach ($this->getHomeStats() as $source) {
            try {
                $stat = $source();
            } catch (\Throwable $e) {
                $this->logHomeSourceError($e);
                $stat = HomeStat::failed('Unavailable', 'fa-solid fa-triangle-exclamation', $e);
            }
            if (null !== $stat) {
                $stats[] = $stat;
            }
        }

        $blocks = [];
        foreach ($this->getHomeActivityBlocks() as $source) {
            try {
                $block = $source();
            } catch (\Throwable $e) {
                $this->logHomeSourceError($e);
                $block = HomeActivityBlock::failed('Unavailable', 'fa-solid fa-triangle-exclamation', $e);
            }
            if (null !== $block) {
                $blocks[] = $block;
            }
        }

        $userIds = [];
        foreach ($blocks as $block) {
            foreach ($block->items as $item) {
                if (null === $item->userName && null !== $item->userId && '' !== $item->userId) {
                    $userIds[] = $item->userId;
                }
            }
        }
        ['names' => $userNames, 'error' => $userNamesError] = $this->userDisplayNameResolver->resolve($userIds);

        return $this->render('@AlchemyAdmin/home.html.twig', [
            'stats' => $stats,
            'blocks' => $blocks,
            'userNames' => $userNames,
            'userNamesError' => $userNamesError,
        ]);
    }

    /**
     * The key figures of the home page. Each one is computed by a closure, so that a failing
     * source (database, Elasticsearch…) only breaks its own card: see createHomeStat().
     *
     * @return iterable<callable(): ?HomeStat>
     */
    protected function getHomeStats(): iterable
    {
        return [];
    }

    /**
     * The "latest activity" tables of the home page, computed like getHomeStats():
     * see createHomeActivityBlock().
     *
     * @return iterable<callable(): ?HomeActivityBlock>
     */
    protected function getHomeActivityBlocks(): iterable
    {
        return [];
    }

    /**
     * @param callable(): array{total: int, last24h?: ?int, last7d?: ?int, last30d?: ?int} $counts
     *
     * @return callable(): HomeStat
     */
    protected function createHomeStat(string $label, string $icon, callable $counts, ?string $url = null, string $format = HomeStat::FORMAT_NUMBER): callable
    {
        return function () use ($label, $icon, $counts, $url, $format): HomeStat {
            try {
                return HomeStat::fromCounts($label, $icon, $counts(), $url, $format);
            } catch (\Throwable $e) {
                $this->logHomeSourceError($e, $label);

                return HomeStat::failed($label, $icon, $e, $url);
            }
        };
    }

    /**
     * @param callable(): iterable<HomeActivityItem> $items
     *
     * @return callable(): HomeActivityBlock
     */
    protected function createHomeActivityBlock(string $title, string $icon, callable $items, ?string $seeAllUrl = null): callable
    {
        return function () use ($title, $icon, $items, $seeAllUrl): HomeActivityBlock {
            try {
                $list = [];
                foreach ($items() as $item) {
                    $list[] = $item;
                }

                return new HomeActivityBlock($title, $icon, $list, $seeAllUrl);
            } catch (\Throwable $e) {
                $this->logHomeSourceError($e, $title);

                return HomeActivityBlock::failed($title, $icon, $e, $seeAllUrl);
            }
        };
    }

    /**
     * The messages of the Messenger "failed" transport. Null when the messenger bundle is not installed.
     */
    protected function createFailedMessagesStat(EntityManagerInterface $em): ?HomeStat
    {
        if (!class_exists(MessengerMessage::class)) {
            return null;
        }

        return $this->createHomeStat(
            'Failed messages',
            'fa-solid fa-bug',
            static fn (): array => ['total' => $em->getRepository(MessengerMessage::class)->count(['queueName' => 'failed'])],
            $this->generateCrudUrl(MessengerMessageCrudController::class),
        )();
    }

    /**
     * @param class-string $crudControllerFqcn
     */
    protected function generateCrudUrl(string $crudControllerFqcn, string $action = Action::INDEX, mixed $entityId = null): string
    {
        /** @var AdminUrlGenerator $adminUrlGenerator */
        $adminUrlGenerator = $this->container->get(AdminUrlGenerator::class);
        $adminUrlGenerator
            ->unsetAll()
            ->setController($crudControllerFqcn)
            ->setAction($action);
        if (null !== $entityId) {
            $adminUrlGenerator->setEntityId($entityId);
        }

        return $adminUrlGenerator->generateUrl();
    }

    protected function createHomeMenuItem(): MenuItemInterface
    {
        return MenuItem::linkToDashboard('Home', 'fa-solid fa-house');
    }

    private function logHomeSourceError(\Throwable $e, ?string $source = null): void
    {
        $this->logger->warning('Admin home: cannot compute "{source}": {message}', [
            'source' => $source ?? 'unknown',
            'message' => $e->getMessage(),
            'exception' => $e,
        ]);
    }

    public function configureCrud(): Crud
    {
        return Crud::new()
            ->setDateFormat('dd/MM/yyyy')
            ->setDateTimeFormat('dd/MM/yyyy HH:mm:ss')
            ->setTimeFormat('HH:mm')
            ->overrideTemplate('layout', '@AlchemyAdmin/layout.html.twig')
            ->overrideTemplate('crud/index', '@AlchemyAdmin/list.html.twig')
            ->overrideTemplate('crud/detail', '@AlchemyAdmin/detail.html.twig')
            ->overrideTemplate('flash_messages', '@AlchemyAdmin/flash_messages.html.twig')
        ;
    }

    public function configureUserMenu(UserInterface $user): UserMenu
    {
        return parent::configureUserMenu($user)
            ->setName($user->getUsername())
            ->displayUserAvatar(false);
    }

    public function configureDashboard(): Dashboard
    {
        return Dashboard::new()
            ->setFaviconPath('favicon.ico')
            ->setTitle('<div>'.($this->adminConfigRegistry->getLogo() ?: '').'<div>'.$this->adminConfigRegistry->getSiteTitle().'</div></div>')
        ;
    }

    protected function createRealtimeMenuItem(): RouteMenuItem
    {
        return MenuItem::linkToRoute('Realtime', 'fa-solid fa-tower-broadcast', RealtimeStatusController::ROUTE_NAME)
            ->setPermission(JwtUser::ROLE_ADMIN);
    }

    /**
     * The "Settings" submenu: the settings of the application, then those
     * shared by every application.
     *
     * @param MenuItemInterface[] $items
     */
    protected function createSettingsMenu(array $items = []): SubMenuItem
    {
        if (class_exists(ConfiguratorEntryCrudController::class)) {
            $items[] = MenuItem::linkTo(ConfiguratorEntryCrudController::class, 'Global Config', 'fa-solid fa-sliders');
        }
        $items[] = $this->createRealtimeMenuItem();

        return MenuItem::subMenu('Settings', 'fa-solid fa-gear')->setSubItems($items);
    }

    protected function createDevMenu(): SubMenuItem
    {
        $subMenu = [];
        if (class_exists(MessengerMessage::class)) {
            $subMenu[] = MenuItem::linkTo(MessengerMessageCrudController::class, 'Messenger Failed Events', 'fa-solid fa-bug');
        }
        $subMenu[] = MenuItem::linkToRoute('Queues', 'fa-solid fa-layer-group', QueuesListController::ROUTE_LIST)->setPermission(JwtUser::ROLE_TECH);
        $subMenu[] = MenuItem::linkToRoute('PHP Info', 'fa-solid fa-circle-info', 'alchemy_admin_phpinfo')->setPermission(JwtUser::ROLE_TECH);

        return MenuItem::subMenu('Dev', 'fa-solid fa-code')->setSubItems($subMenu)->setPermission(JwtUser::ROLE_TECH);
    }

    #[Required]
    public function setAdminConfigRegistry(AdminConfigRegistry $adminConfigRegistry): void
    {
        $this->adminConfigRegistry = $adminConfigRegistry;
    }

    #[Required]
    public function setUserDisplayNameResolver(UserDisplayNameResolver $userDisplayNameResolver): void
    {
        $this->userDisplayNameResolver = $userDisplayNameResolver;
    }

    #[Required]
    public function setLogger(LoggerInterface $logger): void
    {
        $this->logger = $logger;
    }
}
