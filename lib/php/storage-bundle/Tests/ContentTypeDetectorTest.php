    public function testDetectOfficeDocuments(): void
    {
        if (!class_exists(\ZipArchive::class)) {
            $this->markTestSkipped('zip extension required');
        }

        $docx = $this->createZip([
            '[Content_Types].xml' => '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>',
            '_rels/.rels' => '<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>',
            'word/document.xml' => '<?xml version="1.0"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"/>',
        ]);
        $zip = $this->createZip(['foo.txt' => 'foo']);

        try {
            $declared = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
            $this->assertSame($declared, $this->detector->checkFile($docx, $declared));
            $this->assertSame('application/zip', $this->detector->detectFromPath($zip));
            // Office documents not recognized by libmagic are seen as their zip container
            $this->assertSame('application/zip', $this->detector->checkFile($zip, $declared));
        } finally {
            unlink($docx);
            unlink($zip);
        }
    }

